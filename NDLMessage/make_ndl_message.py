# Builds the Norton Design Lab, LLC message (LANDSCAPE 800x480) for the BWRY panel.
# Output: ndl_message.h (2 bpp, 4 px/byte, row-major landscape; 0=blk 1=wht 2=yel 3=red) + preview PNG.
from collections import Counter
from PIL import Image, ImageDraw, ImageFont
W, H, SS = 800, 480, 3
LOGO = "/home/sara/Norton Design Lab Documents/Norton Design Lab logo.bmp"
FONT = "/usr/local/share/fonts/m/Montserrat_VariableFont_wght.ttf"
BLACK, WHITE, YELLOW, RED = 0, 1, 2, 3
RGB = {BLACK: (20, 20, 20), WHITE: (225, 225, 220), YELLOW: (240, 175, 10), RED: (160, 40, 40)}
pal = [c for i in range(4) for c in RGB[i]]
pal += [0] * (768 - len(pal))

def font(size, weight):
    f = ImageFont.truetype(FONT, size)
    f.set_variation_by_axes([weight])
    return f

big = Image.new("P", (W * SS, H * SS), WHITE)
big.putpalette(pal)
d = ImageDraw.Draw(big)

# monogram: dark navy -> black, grey grid dropped
logo = Image.open(LOGO).convert("L").crop((30, 30, 335, 278))
mono = logo.point(lambda v: 0 if v < 110 else 255)
mw = 300 * SS
mono = mono.resize((mw, round(mono.height * mw / mono.width)), Image.LANCZOS).point(lambda v: 0 if v < 128 else 255)
mx, my = 35 * SS, (H * SS - mono.height) // 2 - 8 * SS
big.paste(BLACK, (mx, my), mono.point(lambda v: 255 if v == 0 else 0))

CX0, CW = 370, 410           # right column
def line(parts, size, y, left=CX0, maxw=CW):
    s = size
    while True:
        fs = [(t, font(s * SS, w), c) for t, w, c in parts]
        tw = sum(f.getlength(t) for t, f, _ in fs)
        if tw <= maxw * SS or s < 10:
            break
        s -= 1
    x = left * SS
    for t, f, c in fs:
        d.text((x, y), t, font=f, fill=c)
        x += f.getlength(t)
    return s

top = my + 20 * SS
s = line([("Norton ", 800, BLACK), ("Design Lab", 400, BLACK), (", LLC", 400, RED)], 40, top)
y = top + int(s * 1.55) * SS
d.rectangle([CX0 * SS, y, (CX0 + CW) * SS, y + 6 * SS], fill=RED)
y += 34 * SS
base = big.copy(); COL_Y = y // SS
d.rectangle([0, (H - 14) * SS, W * SS, H * SS], fill=YELLOW)  # (drawn below on both)
lines = [("Better Incentives.", BLACK), ("Cleaner Data.", BLACK), ("Stronger Sales Execution.", RED)]
size = 30
while max(font(size * SS, 500).getlength(t) for t, _ in lines) > CW * SS:
    size -= 1
for t, c in lines:
    line([(t, 500, c)], size, y)
    y += int(size * 1.7) * SS
d.rectangle([0, (H - 14) * SS, W * SS, H * SS], fill=YELLOW)


def encode(img):
    bp = list(img.get_flattened_data()) if hasattr(img, "get_flattened_data") else list(img.getdata())
    px = []
    for yy in range(H):
        for xx in range(W):
            blk = [bp[(yy * SS + j) * W * SS + xx * SS + i] for j in range(SS) for i in range(SS)]
            px.append(Counter(blk).most_common(1)[0][0])
    out = bytearray()
    for i in range(0, len(px), 4):
        out.append(sum((px[i + k] & 3) << (6 - 2 * k) for k in range(4)))
    return px, out

def preview(px, name):
    q = Image.new("P", (W, H)); q.putpalette(pal); q.putdata(px); q.convert("RGB").save(name)

def emit(f, name, out):
    f.write("const uint8_t %s[%d] PROGMEM = {\n" % (name, len(out)))
    for i in range(0, len(out), 24):
        f.write(",".join("0x%02x" % v for v in out[i:i + 24]) + ",\n")
    f.write("};\n")

# base also needs the yellow bar
bd = ImageDraw.Draw(base); bd.rectangle([0, (H - 14) * SS, W * SS, H * SS], fill=YELLOW)
px_full, out_full = encode(big)
px_base, out_base = encode(base)
preview(px_full, "ndl_message_preview.png"); preview(px_base, "ndl_base_preview.png")
with open("ndl_message.h", "w") as f:
    f.write("// generated by make_ndl_message.py - LANDSCAPE 800x480, 2bpp, MSB-first, 0=blk 1=wht 2=yel 3=red\n")
    f.write("#pragma once\n#include <pgmspace.h>\n")
    f.write("#define NDL_COL_X %d\n#define NDL_COL_W %d\n#define NDL_COL_Y %d\n" % (CX0, CW, COL_Y))
    emit(f, "NDL_MSG", out_full)    # logo + name + tagline
    emit(f, "NDL_BASE", out_base)   # logo + name + rule, no tagline (banner messages go in the column)
